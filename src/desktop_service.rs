//! Frontend-independent desktop application services.
//!
//! Tauri is deliberately absent here. Tests can send the exact IPC requests to
//! this module without opening a window or automating user input. The service
//! owns its database/output directory. ROMs remain read-only; Choose save
//! explicitly links a backed-up battery file for deposit/withdrawal publication.

use crate::{
    gen3::{EmeraldSave, Location, Pokemon},
    linked_save::LinkedSaves,
    overlay::{OverlayManifest, VirtualRom},
    registry::DefinitionBundle,
    store::{ManagedSave, ManagedStore, RomLibraryEntry},
    transfer,
};
use anyhow::{ensure, Context, Result};
use serde::Deserialize;
use serde_json::{json, Value};
use std::{
    collections::HashMap,
    fs,
    io::{Read, Write},
    path::{Path, PathBuf},
    sync::Arc,
};
use uuid::Uuid;

mod playback;
use playback::ActivePlayback;

/// Typed IPC inputs reject misspelled fields and arbitrary command names.
/// Choose save explicitly authorizes publishing to that file; other output paths
/// are generated by the service rather than supplied as arbitrary IPC destinations.
#[derive(Deserialize)]
#[serde(tag = "action", rename_all = "snake_case", deny_unknown_fields)]
enum Request {
    // Empty struct variants (rather than unit variants) make Serde enforce
    // deny_unknown_fields even on commands that intentionally take no arguments.
    Overview {},
    AddRom {
        path: String,
    },
    ImportSave {
        rom_hash: String,
        path: String,
    },
    ChooseSave {
        rom_hash: String,
        path: String,
    },
    RemoveGame {
        rom_hash: String,
    },
    RecoverSave {
        save_id: i64,
        expected_revision: i64,
        expected_file_sha256: String,
    },
    SaveView {
        save_id: i64,
    },
    VaultList {
        #[serde(default)]
        query: String,
    },
    Deposit {
        save_id: i64,
        expected_revision: i64,
        locations: Vec<Location>,
        move_from_managed: bool,
    },
    PreviewWithdraw {
        save_id: i64,
        vault_id: i64,
        box_index: usize,
        slot: usize,
    },
    Withdraw {
        save_id: i64,
        expected_revision: i64,
        vault_id: i64,
        box_index: usize,
        slot: usize,
    },
    Undo {
        save_id: i64,
        expected_revision: i64,
    },
    ExportSave {
        save_id: i64,
    },
    Backup {},
    IntegrityCheck {},
    History {
        save_id: Option<i64>,
    },
    RunHeadless {
        rom_hash: String,
        save_id: Option<i64>,
        core_path: String,
        frames: usize,
    },
    EmulatorDefaults {},
    EmulatorStatus {},
    EmulatorControl {
        session_id: String,
        buttons: u16,
        ack: Option<u64>,
        paused: Option<bool>,
    },
    EmulatorStop {
        session_id: String,
    },
    EmulatorDiscard {
        session_id: String,
    },
}

/// One application workspace. Immutable definition snapshots are cached by hash
/// so listing a thousand individuals does not decode a full rules bundle per row.
pub struct DesktopService {
    root: PathBuf,
    store: ManagedStore,
    definitions: HashMap<String, Arc<DefinitionBundle>>,
    links: Arc<LinkedSaves>,
    playback: Option<ActivePlayback>,
}

impl DesktopService {
    /// Open application-owned storage, preserving a consistent old-schema backup
    /// before migration. Existing non-SQLite files are refused.
    pub fn open(path: impl AsRef<Path>) -> Result<Self> {
        fs::create_dir_all(path.as_ref())?;
        let root = path.as_ref().canonicalize()?;
        let database = root.join("vault.sqlite");
        // Lock before migrating SQLite, so a second desktop instance cannot
        // modify even schema metadata before discovering an active workspace.
        let links = Arc::new(LinkedSaves::open(&root)?);
        if database.exists() || database.is_symlink() {
            let metadata = fs::symlink_metadata(&database)?;
            ensure!(
                metadata.is_file() && !metadata.is_symlink(),
                "workspace database must be a regular file"
            );
            let mut magic = [0u8; 16];
            fs::File::open(&database)?.read_exact(&mut magic)?;
            ensure!(
                &magic == b"SQLite format 3\0",
                "existing vault.sqlite is not a SQLite database; refused to overwrite it"
            );
            let old = rusqlite::Connection::open_with_flags(
                &database,
                rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY,
            )?;
            let version: i64 = old.pragma_query_value(None, "user_version", |row| row.get(0))?;
            if version == 1 || version == 2 {
                let backups = owned_directory(&root, "backups")?;
                let backup = backups.join(format!("before-schema-3-{}.sqlite", Uuid::new_v4()));
                // SQLite's backup API includes a consistent view of any WAL; a
                // filesystem copy alone would not guarantee a recoverable snapshot.
                fs::OpenOptions::new()
                    .write(true)
                    .create_new(true)
                    .open(&backup)?;
                old.backup(rusqlite::DatabaseName::Main, &backup, None)?;
                let copy = rusqlite::Connection::open_with_flags(
                    &backup,
                    rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY,
                )?;
                let status: String =
                    copy.pragma_query_value(None, "integrity_check", |row| row.get(0))?;
                ensure!(status == "ok", "pre-migration backup integrity failed");
            }
        }
        let store = ManagedStore::open(&database)?;
        // Unfinished transfers are reconciled using the committed DB snapshot.
        // Keep a conflict inspectable; mutation preflight will explain/block it.
        let _ = links.recover(&store);
        Ok(Self {
            root,
            store,
            definitions: HashMap::new(),
            links,
            playback: None,
        })
    }

    /// Handle one request through the same real services as the CLI. The Tauri
    /// shell serializes access; SQLite revision checks also guard other processes.
    pub fn dispatch(&mut self, request: Value) -> Result<Value> {
        ensure!(
            serde_json::to_vec(&request)?.len() <= 128 * 1024,
            "desktop request is too large"
        );
        let request =
            serde_json::from_value::<Request>(request).context("invalid desktop request")?;
        let changed_save = match &request {
            Request::Deposit { save_id, .. }
            | Request::Withdraw { save_id, .. }
            | Request::Undo { save_id, .. } => Some(*save_id),
            Request::RunHeadless { save_id, .. } => *save_id,
            _ => None,
        };
        if let Some(id) = changed_save {
            self.links.recover(&self.store)?;
            if self.links.link(id)?.is_some() {
                self.links.preflight(&self.store.save(id)?)?;
                let links = self.links.clone();
                self.store.set_save_writer(Some(Box::new(
                    move |save_id, revision, before, after| {
                        ensure!(id == save_id, "linked operation changed the wrong save");
                        links.publish(save_id, revision, before, after)
                    },
                )));
            }
        }
        // The closure contains every early `?`, so cleanup/recovery runs on both
        // successful SQL commits and failures after the file has been published.
        let result = (|| -> Result<Value> {
            match request {
                Request::Overview {} => self.overview(),
                Request::EmulatorDefaults {} => {
                    Ok(json!({"core_path":Self::default_emulator_core()}))
                }
                Request::EmulatorStatus {} => Ok(self.emulator_status()),
                Request::EmulatorControl {
                    session_id,
                    buttons,
                    ack,
                    paused,
                } => self.control_emulator(&session_id, buttons, ack, paused),
                Request::EmulatorStop { session_id } => self.stop_emulator(&session_id),
                Request::EmulatorDiscard { session_id } => self.discard_emulator(&session_id),
                Request::AddRom { path } => self.add_rom(&path),
                Request::ChooseSave { rom_hash, path } => self.choose_save(&rom_hash, &path),
                Request::RemoveGame { rom_hash } => {
                    self.store.remove_rom(&rom_hash)?;
                    Ok(
                        json!({"message":"Game removed from the library. ROM, saves, Vault records and history retained."}),
                    )
                }
                Request::RecoverSave {
                    save_id,
                    expected_revision,
                    expected_file_sha256,
                } => {
                    self.links.resolve(
                        &self.store,
                        save_id,
                        expected_revision,
                        &expected_file_sha256,
                    )?;
                    Ok(
                        json!({"message":"Chosen save restored from committed Vault state; conflicting file retained in backups."}),
                    )
                }
                Request::ImportSave { rom_hash, path } => {
                    let (rom, definitions) = self.load_rom(&rom_hash)?;
                    let definitions=definitions.context("no reviewed save codec for this ROM; identification alone does not establish compatibility")?;
                    let profile = transfer::profile_for(&rom, &definitions)?;
                    let (_, bytes) = read_source(Path::new(&path), 128 * 1024)?;
                    let warnings = EmeraldSave::parse(&bytes)?.warnings;
                    let id =
                        transfer::import_save(&mut self.store, &profile, &definitions, &bytes)?;
                    Ok(
                        json!({"save_id":id,"revision":0,"message":"Save copied into managed storage. Original retained.","warnings":warnings}),
                    )
                }
                Request::SaveView { save_id } => self.save_view(save_id),
                Request::VaultList { query } => self.vault_list(&query),
                Request::Deposit {
                    save_id,
                    expected_revision,
                    locations,
                    move_from_managed,
                } => {
                    ensure!(
                        locations.len() <= 426,
                        "selection exceeds the supported save capacity"
                    );
                    let save = self.store.save(save_id)?;
                    let definitions = self.definitions_for_save(&save)?;
                    let revision = transfer::deposit_at_revision(
                        &mut self.store,
                        save_id,
                        expected_revision,
                        &definitions,
                        &locations,
                        move_from_managed,
                    )?;
                    Ok(
                        json!({"save_id":save_id,"revision":revision,"message":format!("Imported {} Pokemon {}.",locations.len(),
                    if move_from_managed {"from the managed PC save"} else {"as copies; source slots retained"})}),
                    )
                }
                Request::PreviewWithdraw {
                    save_id,
                    vault_id,
                    box_index,
                    slot,
                } => {
                    let save = self.store.save(save_id)?;
                    let definitions = self.definitions_for_save(&save)?;
                    let record = self.store.vault(vault_id)?;
                    let report = transfer::preview(&self.store, &record, &save, &definitions)?;
                    let empty = EmeraldSave::parse(&save.bytes)?
                        .box_record(box_index, slot)?
                        .iter()
                        .all(|b| *b == 0);
                    Ok(
                        json!({"report":report,"revision":save.revision,"destination_slot_empty":empty}),
                    )
                }
                Request::Withdraw {
                    save_id,
                    expected_revision,
                    vault_id,
                    box_index,
                    slot,
                } => {
                    let save = self.store.save(save_id)?;
                    let definitions = self.definitions_for_save(&save)?;
                    let revision = transfer::withdraw_at_revision(
                        &mut self.store,
                        save_id,
                        expected_revision,
                        vault_id,
                        &definitions,
                        box_index,
                        slot,
                    )?;
                    Ok(
                        json!({"save_id":save_id,"revision":revision,"message":"Pokemon removed from the Vault and withdrawn into the selected save."}),
                    )
                }
                Request::Undo {
                    save_id,
                    expected_revision,
                } => {
                    let revision = self.store.undo_at_revision(save_id, expected_revision)?;
                    Ok(
                        json!({"save_id":save_id,"revision":revision,"message":"Latest operation rolled back together with its Vault changes."}),
                    )
                }
                Request::ExportSave { save_id } => self.export_save(save_id),
                Request::Backup {} => {
                    let directory = owned_directory(&self.root, "backups")?;
                    let path = directory.join(format!("vault-{}.sqlite", Uuid::new_v4()));
                    self.store.export_backup(&path)?;
                    Ok(
                        json!({"path":path,"message":"Verified database backup created, including originals and history."}),
                    )
                }
                Request::IntegrityCheck {} => {
                    self.store.integrity_check()?;
                    Ok(json!({"message":"Database structure and stored content hashes are valid."}))
                }
                Request::History { save_id } => {
                    Ok(serde_json::to_value(self.store.history(save_id)?)?)
                }
                Request::RunHeadless {
                    rom_hash,
                    save_id,
                    core_path,
                    frames,
                } => {
                    ensure!(
                        (1..=3600).contains(&frames),
                        "diagnostic frame count must be 1..3600"
                    );
                    let (rom, definitions) = self.load_rom(&rom_hash)?;
                    let core = Path::new(&core_path);
                    let result = if let Some(id) = save_id {
                        let definitions = definitions
                            .context("managed emulation requires reviewed definitions")?;
                        transfer::emulate_managed(
                            &mut self.store,
                            id,
                            &definitions,
                            core,
                            &rom,
                            frames,
                        )?
                    } else {
                        crate::emulator::run_headless(core, &rom, None, frames)?
                    };
                    Ok(serde_json::to_value(result)?)
                }
            }
        })();
        self.store.set_save_writer(None);
        if changed_save.is_some() {
            self.links.recover(&self.store)?;
        }
        result
    }

    /// Choosing the same canonical filename refreshes the same managed save ID.
    /// New emulator progress is validated, not silently overwritten by an old view.
    fn choose_save(&mut self, rom_hash: &str, path: &str) -> Result<Value> {
        ensure!(
            self.playback.is_none(),
            "Stop & save the built-in game before choosing or refreshing a save"
        );
        self.links.recover(&self.store)?;
        let (rom, definitions) = self.load_rom(rom_hash)?;
        let definitions = definitions.context("no reviewed save codec for this ROM")?;
        let profile = transfer::profile_for(&rom, &definitions)?;
        // Check the supplied leaf before resolving directory aliases such as NOXgames.
        let bytes = crate::linked_save::read_regular(Path::new(path), 128 * 1024)?;
        let path = Path::new(path).canonicalize()?;
        let parsed = EmeraldSave::parse(&bytes)?;
        for mon in parsed.pokemon()? {
            ensure!(
                definitions.species.contains_key(&mon.species_id)
                    && mon
                        .moves
                        .iter()
                        .filter(|id| **id != 0)
                        .all(|id| definitions.moves.contains_key(id)),
                "unresolved species or move in chosen save"
            );
        }
        let id = if let Some(link) = self.links.find_path(&path)? {
            let save = self.store.save(link.save_id)?;
            ensure!(
                save.profile == profile,
                "chosen file is already linked to an incompatible game profile"
            );
            if save.bytes != bytes {
                self.store
                    .commit(&save, &bytes, "external-save-refresh", &[], &[])?;
            }
            save.id
        } else {
            transfer::import_save(&mut self.store, &profile, &definitions, &bytes)?
        };
        let save = self.store.save(id)?;
        self.links.bind(path.clone(), &save)?;
        Ok(
            json!({"save_id":id,"revision":save.revision,"linked_path":path,
            "message":"Save chosen. Deposits, withdrawals and undo now update this same file with backups. Close the external emulator before transferring."}),
        )
    }

    // Library changes never modify the selected cartridge file. Unknown images
    // may be listed with identification diagnostics but receive no save parser.
    fn add_rom(&mut self, path: &str) -> Result<Value> {
        let (path, bytes) = read_source(Path::new(path), 32 * 1024 * 1024)?;
        let identity = crate::rom::identify(&bytes)?;
        let definition = match crate::extraction::extract_reviewed_emerald(&bytes) {
            Ok(bundle) => Some(bundle),
            Err(error)
                if identity.sha256 == crate::rom::EMERALD_RETAIL_SHA256
                    || identity.sha256 == transfer::LOCAL_MODERN_SHA256 =>
            {
                return Err(error).context("reviewed ROM extraction failed")
            }
            Err(_) => None,
        };
        let definition_hash = definition
            .as_ref()
            .map(|bundle| {
                self.store
                    .register_definition(&serde_json::to_value(bundle)?)
            })
            .transpose()?;
        let entry = RomLibraryEntry {
            hash: identity.sha256.clone(),
            source_path: path.to_string_lossy().into_owned(),
            identity: serde_json::to_value(identity)?,
            definition_hash,
        };
        self.store.register_rom(&entry)?;
        self.game_view(&entry)
    }

    // Cache by immutable JSON snapshot hash rather than a mutable filename.
    fn load_definition(&mut self, hash: &str) -> Result<Arc<DefinitionBundle>> {
        if let Some(bundle) = self.definitions.get(hash) {
            return Ok(bundle.clone());
        }
        let value = self.store.definition(hash)?;
        let bundle: DefinitionBundle = serde_json::from_value(value)?;
        bundle.validate()?;
        let bundle = Arc::new(bundle);
        self.definitions.insert(hash.into(), bundle.clone());
        Ok(bundle)
    }

    fn definitions_for_save(&mut self, save: &ManagedSave) -> Result<Arc<DefinitionBundle>> {
        // Validate existing library rows even when searching for an absent one;
        // a corrupt row must never masquerade as an intentionally removed game.
        if let Some(game) = self
            .store
            .list_roms()?
            .into_iter()
            .find(|game| game.hash == save.profile.rom_sha256)
        {
            if let Some(hash) = game.definition_hash {
                let bundle = self.load_definition(&hash)?;
                transfer::validate_context(&save.profile, &bundle)?;
                return Ok(bundle);
            }
        }
        // Removing a game hides its ROM path, not the immutable rules needed
        // to manage its retained Pokemon. Only an exact profile match is valid.
        for hash in self.store.definition_hashes()? {
            let bundle = self.load_definition(&hash)?;
            if transfer::validate_context(&save.profile, &bundle).is_ok() {
                return Ok(bundle);
            }
        }
        anyhow::bail!("no immutable definition snapshot matches this save profile")
    }

    // Re-read and hash the source whenever it is needed for runtime/import. A
    // library entry does not authorize silently using a replacement at that path.
    fn load_rom(&mut self, hash: &str) -> Result<(VirtualRom, Option<Arc<DefinitionBundle>>)> {
        let game = self.store.rom(hash)?;
        let (_, bytes) = read_source(Path::new(&game.source_path), 32 * 1024 * 1024)?;
        ensure!(
            crate::sha256(&bytes) == hash,
            "ROM changed since identification; add and review it again"
        );
        let manifest = OverlayManifest::identity(&bytes);
        let rom = VirtualRom::new(bytes.into(), manifest)?;
        let definitions = game
            .definition_hash
            .map(|hash| self.load_definition(&hash))
            .transpose()?;
        Ok((rom, definitions))
    }

    fn game_view(&mut self, game: &RomLibraryEntry) -> Result<Value> {
        let mut diagnostics = game.identity["diagnostics"]
            .as_array()
            .cloned()
            .unwrap_or_default();
        let supported = if let Some(hash) = &game.definition_hash {
            let bundle = self.load_definition(hash)?;
            ensure!(
                bundle.rom_sha256 == game.hash,
                "ROM/definition library mismatch"
            );
            diagnostics.push(json!("Partial source rules; custom-resource installation and cross-profile transfers are unavailable."));
            true
        } else {
            false
        };
        let title = game.identity["known_game"]
            .as_str()
            .unwrap_or_else(|| game.identity["title"].as_str().unwrap_or("Untitled ROM"));
        Ok(
            json!({"hash":game.hash,"source_path":game.source_path,"title":title,
            "platform":game.identity["platform"],"game_code":game.identity["game_code"],
            "classification":game.identity["classification"],"import_supported":supported,"diagnostics":diagnostics}),
        )
    }

    fn overview(&mut self) -> Result<Value> {
        let mut games = Vec::new();
        for game in self.store.list_roms()? {
            games.push(self.game_view(&game)?);
        }
        let mut saves = Vec::new();
        for id in self.store.list_save_ids()? {
            let save = self.store.save(id)?;
            let (mut sync_status, linked_path) = self.links.status(&save)?;
            if self.emulator_owns_save(id) {
                sync_status = "emulating";
            }
            let definitions = match self.definitions_for_save(&save) {
                Ok(definitions) => definitions,
                Err(error) => {
                    // A migrated CLI database may have saves before it has ROM
                    // library rows. Keep the library usable so the user can add
                    // its matching ROM; unknown counts must not appear as zero.
                    saves.push(json!({"id":id,"revision":save.revision,"game_hash":save.profile.rom_sha256,
                        "definition_id":save.profile.definition_id,"party_count":null,"pc_count":null,
                        "linked_path":linked_path,"sync_status":sync_status,
                        "warnings":[format!("Add the matching ROM definition before viewing this save: {error:#}")]}));
                    continue;
                }
            };
            let parsed = EmeraldSave::parse(&save.bytes)?;
            let pokemon = parsed.pokemon()?;
            // Resolve source IDs before publishing a count as a supported save.
            for mon in &pokemon {
                ensure!(
                    definitions.species.contains_key(&mon.species_id),
                    "unresolved species in save {id}"
                );
            }
            let party = pokemon
                .iter()
                .filter(|mon| matches!(mon.location, Location::Party { .. }))
                .count();
            saves.push(json!({"id":id,"revision":save.revision,"game_hash":save.profile.rom_sha256,
                "definition_id":save.profile.definition_id,"party_count":party,"pc_count":pokemon.len()-party,
                "warnings":parsed.warnings,"linked_path":linked_path,"sync_status":sync_status}));
        }
        Ok(
            json!({"workspace_path":self.root,"games":games,"saves":saves,"vault_count":self.store.list_vault()?.len()}),
        )
    }

    fn save_view(&mut self, id: i64) -> Result<Value> {
        let save = self.store.save(id)?;
        let (mut sync_status, linked_path) = self.links.status(&save)?;
        if self.emulator_owns_save(id) {
            sync_status = "emulating";
        }
        let external_sha256 = linked_path
            .as_ref()
            .and_then(|path| crate::linked_save::read_regular(path, 128 * 1024).ok())
            .map(|bytes| crate::sha256(&bytes));
        let definitions = self.definitions_for_save(&save)?;
        let parsed = EmeraldSave::parse(&save.bytes)?;
        let pokemon = parsed
            .pokemon()?
            .into_iter()
            .map(|mon| pokemon_view(&mon, &definitions, Some(&mon.location), None, None))
            .collect::<Result<Vec<_>>>()?;
        Ok(
            json!({"id":id,"revision":save.revision,"profile":save.profile,"warnings":parsed.warnings,
            "pokemon":pokemon,"box_count":14,"slots_per_box":30,"linked_path":linked_path,"sync_status":sync_status,"external_sha256":external_sha256}),
        )
    }

    fn vault_list(&mut self, query: &str) -> Result<Value> {
        let query = query.trim().to_lowercase();
        let mut output = Vec::new();
        for record in self.store.list_vault()? {
            let hash = record.source_definition["bundle_sha256"]
                .as_str()
                .context("missing source definition reference")?;
            let definitions = self.load_definition(hash)?;
            transfer::validate_context(&record.source_profile, &definitions)?;
            let origin = record.normalized["record"]["location"].clone();
            let origin = serde_json::from_value::<Location>(origin)
                .context("missing source record location")?;
            let mon = crate::gen3::decode_record(&record.raw, origin)?;
            let view = pokemon_view(&mon, &definitions, None, Some(record.id), Some(record.uuid))?;
            let search = format!(
                "{} {} {} {} {}",
                mon.nickname,
                view["species_name"].as_str().unwrap_or(""),
                definitions.id,
                record.uuid,
                mon.species_id
            )
            .to_lowercase();
            if query.is_empty() || search.contains(&query) {
                output.push(view);
            }
        }
        Ok(json!(output))
    }

    fn export_save(&mut self, id: i64) -> Result<Value> {
        let save = self.store.save(id)?;
        let definitions = self.definitions_for_save(&save)?;
        EmeraldSave::parse(&save.bytes)?.pokemon()?;
        let parent = owned_directory(&self.root, "exports")?;
        let path = parent.join(format!(
            "save-{id}-revision-{}-{}",
            save.revision,
            Uuid::new_v4()
        ));
        fs::create_dir(&path)?;
        write_new(&path.join("working.sav"), &save.bytes)?;
        write_new(
            &path.join("profile.json"),
            &serde_json::to_vec_pretty(&save.profile)?,
        )?;
        write_new(
            &path.join("definitions.json"),
            &serde_json::to_vec_pretty(definitions.as_ref())?,
        )?;
        let hash = crate::sha256(&save.bytes);
        write_new(
            &path.join("receipt.json"),
            &serde_json::to_vec_pretty(&json!({"save_id":id,
            "revision":save.revision,"save_sha256":hash,"profile_sha256":save.profile.fingerprint()}))?,
        )?;
        ensure!(
            fs::read(path.join("working.sav"))? == save.bytes,
            "export verification failed"
        );
        Ok(
            json!({"path":path,"save_sha256":hash,"message":format!("Exported save {id}, revision {} into a new directory.",save.revision)}),
        )
    }
}

// Decode a view only against its immutable source rules. Unknown fields stay in
// raw storage; this view omits the byte vector to keep lists compact and readable.
fn pokemon_view(
    mon: &Pokemon,
    definitions: &DefinitionBundle,
    location: Option<&Location>,
    vault_id: Option<i64>,
    uuid: Option<Uuid>,
) -> Result<Value> {
    let species = definitions
        .species
        .get(&mon.species_id)
        .context("species definition is missing")?;
    let mut individual = serde_json::to_value(mon)?;
    individual
        .as_object_mut()
        .context("invalid individual")?
        .remove("raw");
    let mut moves = Vec::new();
    for i in 0..4 {
        if mon.moves[i] == 0 {
            continue;
        }
        let definition = definitions
            .moves
            .get(&mon.moves[i])
            .context("move definition is missing")?;
        moves.push(
            json!({"id":mon.moves[i],"name":definition.name,"pp":mon.pp[i],
            "pp_ups":mon.pp_ups[i],"definition":definition}),
        );
    }
    let evolutions=definitions.evolutions.iter().filter(|rule|rule.from==mon.species_id || rule.to==mon.species_id)
        .map(|rule|json!({"from_name":definitions.species[&rule.from].name,
            "to_name":definitions.species[&rule.to].name,"method_namespace":rule.method_namespace,"requirements":rule.requirements})).collect::<Vec<_>>();
    let mut types = species.data["type_ids"]
        .as_array()
        .map(|types| {
            types
                .iter()
                .filter_map(Value::as_u64)
                .map(type_name)
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    // Emerald repeats a single type in both table fields. Keep that source data
    // intact but present one label instead of a misleading "Fire / Fire" badge.
    types.dedup();
    Ok(
        json!({"location":location,"vault_id":vault_id,"uuid":uuid,"species_id":mon.species_id,
        "species_name":species.name,"nickname":mon.nickname,"level":mon.party_level,"shiny":mon.shiny,
        "type_names":types,"source_game":definitions.id,"raw_sha256":crate::sha256(&mon.raw),
        "moves":moves,"individual":individual,"species":species,"evolutions":evolutions,"limitations":species.missing}),
    )
}

// These type labels apply only inside the reviewed vanilla Emerald adapter.
fn type_name(id: u64) -> String {
    const TYPES: [&str; 18] = [
        "Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel",
        "Mystery", "Fire", "Water", "Grass", "Electric", "Psychic", "Ice", "Dragon", "Dark",
    ];
    TYPES
        .get(id as usize)
        .map(|name| (*name).to_string())
        .unwrap_or_else(|| format!("Unknown type {id}"))
}

// Refuse directories/devices, cap reads even if a file grows, and notice ordinary
// concurrent emulator writes. This helper never opens an input with write access.
fn read_source(path: &Path, limit: usize) -> Result<(PathBuf, Vec<u8>)> {
    let path = path
        .canonicalize()
        .with_context(|| format!("locate {}", path.display()))?;
    let mut file = fs::File::open(&path)?;
    let before = file.metadata()?;
    ensure!(
        before.is_file() && before.len() <= limit as u64,
        "input is not a supported regular file or is too large"
    );
    let mut bytes = Vec::new();
    (&mut file).take(limit as u64 + 1).read_to_end(&mut bytes)?;
    let after = file.metadata()?;
    ensure!(
        bytes.len() <= limit
            && before.len() == after.len()
            && before.modified().ok() == after.modified().ok(),
        "input changed while reading; close the emulator and try again"
    );
    Ok((path, bytes))
}

// Outputs remain beneath the application root. Existing symlinked output folders
// are refused instead of redirecting an export into an unrelated project.
fn owned_directory(root: &Path, name: &str) -> Result<PathBuf> {
    let path = root.join(name);
    if !path.exists() && !path.is_symlink() {
        fs::create_dir(&path)?;
    }
    let metadata = fs::symlink_metadata(&path)?;
    ensure!(
        metadata.is_dir() && !metadata.is_symlink(),
        "application output directory is not a regular directory"
    );
    Ok(path)
}

// New file creation ensures exports cannot overwrite a source or older backup.
fn write_new(path: &Path, bytes: &[u8]) -> Result<()> {
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    Ok(())
}
